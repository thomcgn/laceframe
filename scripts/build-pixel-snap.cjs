/* global __dirname */
// Rebuild the committed, import-free Rust WASM used by both Main and worker.
const { spawnSync } = require("node:child_process");
const fs = require("node:fs"),
  path = require("node:path"),
  { createHash } = require("node:crypto");
const root = path.resolve(__dirname, ".."),
  crate = path.join(root, "native/pixel-snap");
const result = spawnSync(
  "cargo",
  ["build", "--release", "--target", "wasm32-unknown-unknown", "--locked"],
  {
    cwd: crate,
    stdio: "inherit",
    env: { ...process.env, RUSTFLAGS: "-C link-arg=--max-memory=134217728" },
  },
);
if (result.error) throw result.error;
if (result.status !== 0) process.exit(result.status || 1);
const bytes = fs.readFileSync(
  path.join(
    crate,
    "target/wasm32-unknown-unknown/release/laceframe_pixel_snap.wasm",
  ),
);
const sha = createHash("sha256").update(bytes).digest("hex");
fs.writeFileSync(
  path.join(root, "src/shared/pixel-snap-wasm.ts"),
  `// Generated by scripts/build-pixel-snap.cjs from MIT-licensed native/pixel-snap.\n// Rust 1.85.1; SHA-256 ${sha}; no WASM host imports; 128 MiB maximum linear memory.\nexport const SNAP_WASM_BASE64 = "${bytes.toString("base64")}";\n`,
);
console.log(`Pixel Snap WASM: ${bytes.length} bytes; SHA-256 ${sha}`);
