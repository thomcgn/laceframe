/* global __dirname */
// Explicit developer build; normal Electron builds use committed WASM/glue offline.
const { spawnSync } = require("node:child_process");
const fs = require("node:fs"),
  path = require("node:path"),
  { createHash } = require("node:crypto");
const root = path.resolve(__dirname, ".."),
  crate = path.join(root, "native/spritefusion"),
  output = path.join(crate, "target/bindgen");
const source = JSON.parse(fs.readFileSync(path.join(crate, "UPSTREAM.json"), "utf8"));
for (const [file, sha] of Object.entries(source.files)) {
  if (createHash("sha256").update(fs.readFileSync(path.join(crate,"vendor",file))).digest("hex") !== sha)
    throw new Error(`Upstream source changed: ${file}`);
}
function run(cmd, args) {
  const r = spawnSync(cmd, args, {
    cwd: crate,
    stdio: "inherit",
    env: { ...process.env, RUSTFLAGS: "-C link-arg=--max-memory=536870912" },
  });
  if (r.error) throw r.error;
  if (r.status !== 0) process.exit(r.status || 1);
}
const version = spawnSync("wasm-bindgen", ["--version"], { encoding: "utf8" });
if (version.status !== 0 || version.stdout.trim() !== "wasm-bindgen 0.2.105")
  throw new Error("Use wasm-bindgen-cli 0.2.105");
run("cargo", [
  "+1.85.1",
  "build",
  "--lib",
  "--release",
  "--target",
  "wasm32-unknown-unknown",
  "--locked",
]);
run("wasm-bindgen", [
  "target/wasm32-unknown-unknown/release/laceframe_spritefusion.wasm",
  "--target",
  "web",
  "--out-dir",
  output,
  "--out-name",
  "spritefusion",
]);
const dest = path.join(root, "src/shared/spritefusion-generated");
fs.mkdirSync(dest, { recursive: true });
for (const file of ["spritefusion.js", "spritefusion.d.ts"])
  fs.copyFileSync(path.join(output, file), path.join(dest, file));
const bytes = fs.readFileSync(path.join(output, "spritefusion_bg.wasm"));
const sha = createHash("sha256").update(bytes).digest("hex");
fs.writeFileSync(
  path.join(dest, "wasm.ts"),
  `// Generated by scripts/build-spritefusion.cjs; Rust 1.85.1 / wasm-bindgen 0.2.105.\n// Original commit 02f9315d73d3219274d17767b36d9a231a6b1f4b; SHA-256 ${sha}\nexport const SPRITEFUSION_WASM_BASE64 = "${bytes.toString("base64")}";\n`,
);
console.log(`Sprite Fusion: ${bytes.length} bytes; ${sha}`);
